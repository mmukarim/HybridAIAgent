import json

from app.langchain_integration.gemini import GeminiChatModel
from app.tools.data_analysis import generate_business_insights
from app.tools.dataset_registry import DatasetRegistry


def interpret_business_insights(analysis_result: dict) -> str:
    """
    Interpret Python-generated business insights using Gemini.
    """

    if not isinstance(analysis_result, dict):
        raise TypeError("Analysis result must be a dictionary.")

    analysis_json = json.dumps(
        analysis_result,
        ensure_ascii=False,
        indent=2,
        allow_nan=False,
    )

    prompt = f"""
You are an experienced business data analyst.

Your task is to interpret analytical results generated by
a deterministic Python analysis engine.

IMPORTANT RULES:
1. Treat the supplied analytical results as the source of truth.
2. Never recalculate or modify numerical results.
3. Never invent missing metrics, facts, or business context.
4. Never assume currency, units, or reporting periods.
5. Clearly distinguish observed facts from interpretations.
6. Label possible explanations as hypotheses, not established facts.
7. Do not claim causation based only on statistical relationships.
8. Do not make recommendations that depend on unavailable information without identifying the assumptions.
9. Explicitly mention limitations in the available data.

Prepare a concise business analysis report containing:

1. Executive Summary
2. Key Findings
3. Business Implications
4. Recommendations
5. Limitations

Use clear, professional business language.

Analytical Results:
{analysis_json}
"""

    chat_model = GeminiChatModel()
    response = chat_model.invoke(prompt)

    if isinstance(response.content, str):
        return response.content

    return "\n".join(
        block["text"]
        for block in response.content
        if isinstance(block, dict) and block.get("type") == "text"
    )


def generate_business_report(
    registry: DatasetRegistry,
    dataset_id: str,
    group_by: str,
    value_column: str,
    operation: str = "sum",
) -> str:

    df = registry.get(dataset_id)

    analysis_result = generate_business_insights(
        df=df,
        group_by=group_by,
        value_column=value_column,
        operation=operation,
    )

    return interpret_business_insights(analysis_result)
